#!/usr/bin/env python3
"""AI-trace screening pass (RESCUE_PLAN_EXHAUSTIVE.md, Part 8.3).

Runs every trace under `--root` through ChampSim ONCE, policy=lru only, and
keeps the ones that actually exercise the LLC: MPKI >= --min-mpki (default 1)
AND nonzero charged write traffic (nvm_writes + sram_writes > 0, the same
columns run_champsim.py already scrapes). Traces that fail either test are
recorded, not silently dropped - that list is the audit trail Scenario 6 of
the contingency playbook demands.

Usage:
    python3 stage5_champsim/screen_ai_traces.py \
        --root /media/kallinath/WD_1_exFAT/SUSCOM-revision/AI_WORKLOADS_CHAMPSIM \
        --outdir results/ai_screen

Writes:
    results/ai_screen/screen_results.csv   (raw lru-only pass, one row/trace)
    results/ai_screen/survivors.manifest   (one path per line - point
                                             experiment.champsim_ai_traces_manifest
                                             at this file for the full batch)
    results/ai_screen/excluded.csv         (trace, mpki, writes, reason)

The screening pass itself uses the SAME warmup/sim instruction counts the
full batch will use (pass --warmup/--sim to match config/suscom_ten_mixes.json
experiment.champsim_warmup / champsim_sim), because a trace that looks idle
under a short warmup can still be write-heavy once warm - screening on a
shorter run than the real batch would silently re-introduce the bug this
script exists to close.
"""
import argparse, csv, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--root', required=True, help='AI traces directory (recursed)')
    ap.add_argument('--outdir', default='results/ai_screen')
    ap.add_argument('--warmup', type=int, default=20_000_000)
    ap.add_argument('--sim', type=int, default=100_000_000)
    ap.add_argument('--nvm-ways', default='12')
    ap.add_argument('--workers', type=int, default=2)
    ap.add_argument('--min-mpki', type=float, default=1.0)
    a = ap.parse_args()

    os.makedirs(a.outdir, exist_ok=True)
    screen_csv = os.path.join(a.outdir, 'screen_results.csv')

    cmd = [sys.executable, os.path.join(HERE, 'run_champsim.py'),
           '--traces', a.root, '--policies', 'lru',
           '--warmup', str(a.warmup), '--sim', str(a.sim),
           '--nvm-ways', a.nvm_ways, '--workers', str(a.workers),
           '--outdir', a.outdir, '--out', screen_csv]
    print('screening pass:', ' '.join(cmd))
    subprocess.run(cmd, check=True)

    survivors, excluded = [], []
    with open(screen_csv, newline='') as f:
        for r in csv.DictReader(f):
            trace = r.get('trace', '')
            try:
                mpki = float(r['mpki']) if r.get('mpki') not in (None, '') else -1.0
            except ValueError:
                mpki = -1.0
            try:
                writes = (float(r['nvm_writes'] or 0) + float(r['sram_writes'] or 0))
            except ValueError:
                writes = 0.0
            status = r.get('status', '')
            if status != 'ok':
                excluded.append((trace, mpki, writes, 'run_status_%s' % status))
            elif mpki < a.min_mpki:
                excluded.append((trace, mpki, writes, 'mpki_below_%.2f' % a.min_mpki))
            elif writes <= 0:
                excluded.append((trace, mpki, writes, 'zero_write_traffic'))
            else:
                survivors.append((trace, mpki, writes))

    with open(os.path.join(a.outdir, 'excluded.csv'), 'w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['trace', 'mpki', 'nvm_plus_sram_writes', 'reason'])
        w.writerows(excluded)

    # survivors.manifest holds champsimtrace filenames (basename, no dir) -
    # matched back against the recursive walk of --root at full-batch time
    # via champsim_ai_traces_manifest. We write the ABSOLUTE resolved path
    # recorded by run_champsim.py's own trace tag instead, one per line, so
    # mfs.py's isabs() check in the manifest reader takes them as-is.
    manifest_path = os.path.join(a.outdir, 'survivors.manifest')
    # run_champsim.py's `trace` field is the basename with .champsimtrace*
    # stripped (see `one()`: tname = basename.split('.champsimtrace')[0]),
    # so recover the real file by re-walking --root and matching prefixes.
    real_files = {}
    for dp, _, fs in os.walk(a.root):
        for fn in fs:
            if '.champsimtrace' in fn and fn.endswith(('.xz', '.gz')):
                tname = fn.split('.champsimtrace')[0]
                real_files.setdefault(tname, os.path.join(dp, fn))

    with open(manifest_path, 'w') as f:
        f.write('# Auto-generated by screen_ai_traces.py - %d of %d AI traces '
                'passed MPKI>=%.2f and nonzero write-traffic screening.\n'
                % (len(survivors), len(survivors) + len(excluded), a.min_mpki))
        f.write('# Point experiment.champsim_ai_traces_manifest at this file.\n')
        missing_lookup = 0
        for trace, mpki, writes in sorted(survivors):
            path = real_files.get(trace)
            if path is None:
                missing_lookup += 1
                continue
            f.write(path + '\n')
        if missing_lookup:
            print('WARNING: %d survivor(s) could not be matched back to a '
                  'real file by basename - inspect manually.' % missing_lookup)

    print('\n%d / %d traces survived screening (MPKI >= %.2f, nonzero writes)'
          % (len(survivors), len(survivors) + len(excluded), a.min_mpki))
    print('manifest:', manifest_path)
    print('excluded list:', os.path.join(a.outdir, 'excluded.csv'))
    if excluded:
        print('excluded traces (see excluded.csv for full reason column):')
        for trace, mpki, writes, reason in excluded:
            print('   %-40s mpki=%-8s writes=%-10s %s' % (trace, mpki, writes, reason))


if __name__ == '__main__':
    main()
