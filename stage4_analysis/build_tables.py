#!/usr/bin/env python3
"""Stage 4: turn raw stage-1/2/3 output into LaTeX table fragments.

Every table is generated from the CSV produced by the corresponding stage, so
nothing is hand-transcribed.  Fragments are written to results/tex/ and are
meant to be \\input into the manuscript.
"""
import argparse, csv, json, os
from collections import defaultdict

TEX_HEAD = ('%% generated by stage4_analysis/build_tables.py -- do not edit by hand\n'
            '%% source: %s\n')


def read_csv(p):
    with open(p) as f:
        return list(csv.DictReader(f))


def f(x, nd=2, dash='--'):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return dash
    return ('%%.%df' % nd) % v


def pct(x, nd=1, dash='--'):
    try:
        return ('%%.%df' % nd) % (100.0 * float(x))
    except (TypeError, ValueError):
        return dash


# --------------------------------------------------------------- stage 1 -----
def table_cross_tech(rows, node, road, opt, out):
    """Cache-level PPA for every technology across capacities."""
    sel = [r for r in rows if r['node_nm'] == str(node) and r['roadmap'] == road
           and r['opt_target'] == opt and r['status'] in ('ok', 'cached')]
    techs = sorted({r['tech'] for r in sel})
    caps = sorted({int(r['capacity_MB']) for r in sel})
    idx = {(r['tech'], int(r['capacity_MB'])): r for r in sel}

    metrics = [('hit_latency_ns', 'Read latency (ns)', 3),
               ('write_latency_ns', 'Write latency (ns)', 3),
               ('hit_energy_nJ', 'Read energy (nJ)', 3),
               ('write_energy_nJ', 'Write energy (nJ)', 3),
               ('leakage_mW', 'Leakage (mW)', 1),
               ('area_mm2', 'Area (mm$^2$)', 3)]

    L = [TEX_HEAD % 'stage1_destiny/results.csv']
    L.append('\\begin{table}[t]\n\\centering\n\\small')
    L.append('\\caption{Cache-level power, performance and area at %d\\,nm (%s devices, '
             '%s-optimised, 8-way, sequential access), modelled with DESTINY~v2. '
             'SOT-MRAM is reported at the two balanced cell geometries identified by the '
             'multi-factor scaling sweep.}' % (node, road, opt))
    L.append('\\label{tab:crosstech_%dnm_%s}' % (node, road.lower()))
    L.append('\\begin{tabular}{ll%s}' % ('r' * len(caps)))
    L.append('\\toprule')
    L.append('Metric & Technology & ' + ' & '.join('%d\\,MB' % c for c in caps) + ' \\\\')
    L.append('\\midrule')
    for m, label, nd in metrics:
        for i, t in enumerate(techs):
            cells = [f(idx[(t, c)][m], nd) if (t, c) in idx else '--' for c in caps]
            first = '\\multirow{%d}{*}{%s}' % (len(techs), label) if i == 0 else ''
            L.append('%s & %s & %s \\\\' % (first, t, ' & '.join(cells)))
        L.append('\\midrule')
    L[-1] = '\\bottomrule'
    L.append('\\end{tabular}\n\\end{table}')
    open(out, 'w').write('\n'.join(L) + '\n')
    return out


def table_relative(rows, node, road, opt, base_tech, out):
    """Every technology expressed relative to SRAM -- the comparison the
    reviewer asked to see replaced by an NVM-vs-NVM one, kept for continuity,
    plus SOT relative to STT-MRAM."""
    sel = [r for r in rows if r['node_nm'] == str(node) and r['roadmap'] == road
           and r['opt_target'] == opt and r['status'] in ('ok', 'cached')]
    idx = {(r['tech'], int(r['capacity_MB'])): r for r in sel}
    caps = sorted({int(r['capacity_MB']) for r in sel})
    techs = [t for t in sorted({r['tech'] for r in sel}) if t != base_tech]

    L = [TEX_HEAD % 'stage1_destiny/results.csv']
    L.append('\\begin{table}[t]\n\\centering\n\\small')
    L.append('\\caption{Change relative to %s at %d\\,nm (%s, %s-optimised). '
             'Negative is better for latency, energy, leakage and area.}'
             % (base_tech, node, road, opt))
    L.append('\\label{tab:rel_%s_%dnm}' % (base_tech.lower(), node))
    L.append('\\begin{tabular}{ll%s}' % ('r' * len(caps)))
    L.append('\\toprule')
    L.append('Metric & vs.\\ %s & ' % base_tech + ' & '.join('%d\\,MB' % c for c in caps) + ' \\\\')
    L.append('\\midrule')
    for m, label in [('hit_latency_ns', 'Read latency'), ('write_latency_ns', 'Write latency'),
                     ('hit_energy_nJ', 'Read energy'), ('write_energy_nJ', 'Write energy'),
                     ('leakage_mW', 'Leakage'), ('area_mm2', 'Area')]:
        for i, t in enumerate(techs):
            cells = []
            for c in caps:
                a, b = idx.get((t, c)), idx.get((base_tech, c))
                try:
                    cells.append('%+.1f\\%%' % (100.0 * (float(a[m]) / float(b[m]) - 1.0)))
                except (TypeError, ValueError, ZeroDivisionError, AttributeError):
                    cells.append('--')
            first = '\\multirow{%d}{*}{%s}' % (len(techs), label) if i == 0 else ''
            L.append('%s & %s & %s \\\\' % (first, t, ' & '.join(cells)))
        L.append('\\midrule')
    L[-1] = '\\bottomrule'
    L.append('\\end{tabular}\n\\end{table}')
    open(out, 'w').write('\n'.join(L) + '\n')
    return out


# --------------------------------------------------------------- stage 3 -----
NICE = {
    'unmanaged': 'Unmanaged (LRU)',
    'lru-hybrid': 'Hybrid array, blind LRU',
    'psc': 'PSC only',
    'vro': 'VRO only',
    'psc-vro': 'PSC-VRO (proposed)',
    'i2wap': 'i2WAP~\\cite{wang2013i2wap}',
    'equalchance': 'EqualChance~\\cite{mittal2014equalchance}',
    'startgap': 'Start-Gap~\\cite{qureshi2009startgap}',
    'sequoia': 'Sequoia~\\cite{jokar2016sequoia}',
    'swwr': 'SWWR~\\cite{agarwal2020thesis}',
    'dwwr': 'DWWR~\\cite{agarwal2020thesis}',
}
ORDER = ['unmanaged', 'lru-hybrid', 'startgap', 'i2wap', 'equalchance',
         'sequoia', 'swwr', 'dwwr', 'psc', 'vro', 'psc-vro']


def table_lifetime(rows, arena, out):
    sel = [r for r in rows if r['arena'] == arena]
    sel.sort(key=lambda r: ORDER.index(r['scheme']) if r['scheme'] in ORDER else 99)
    L = [TEX_HEAD % 'stage3_hycsim/lifetime_*.csv']
    L.append('\\begin{table}[t]\n\\centering\n\\small')
    L.append('\\caption{Write-variation and lifetime on the %s array. All schemes are '
             'parameter-tuned on a trace prefix and evaluated on its non-overlapping suffix on the same '
             'physical array, so the comparison isolates the management policy. '
             '$RLI_{\\mathrm{direct}}$ is measured from the peak frame write count; '
             '$RLI_{\\mathrm{proxy}}$ is the closed-form estimator of Eq.~(5). '
             'WA is the write amplification the mechanism itself introduces.}' % arena)
    L.append('\\label{tab:lifetime_%s}' % arena.replace('-', ''))
    L.append('\\begin{tabular}{lrrrrrrr}')
    L.append('\\toprule')
    L.append('Scheme & $\\mu$ & InterV & IntraV & max writes & '
             '$RLI_{\\mathrm{direct}}$ & $RLI_{\\mathrm{proxy}}$ & WA \\\\')
    L.append(' & & (\\%) & (\\%) & & (\\%) & (\\%) & ($\\times$) \\\\')
    L.append('\\midrule')
    for r in sel:
        L.append('%s & %s & %s & %s & %s & %s & %s & %s \\\\' % (
            NICE.get(r['scheme'], r['scheme']), f(r['mu'], 1), pct(r['interv']),
            pct(r['intrav']), f(r['max_write'], 0), pct(r.get('rli_direct')),
            pct(r.get('rli_proxy')), f(r.get('write_amplification'), 3)))
    L.append('\\bottomrule')
    L.append('\\end{tabular}\n\\end{table}')
    open(out, 'w').write('\n'.join(L) + '\n')
    return out


def table_composition(abl, out):
    L = [TEX_HEAD % 'stage3_hycsim/ablation_*.json']
    L.append('\\begin{table}[t]\n\\centering\n\\small')
    L.append('\\caption{Composition of PSC and VRO. Relative lifetime improvement is a '
             'ratio of ratios, so the null hypothesis for two independent mechanisms is '
             'multiplicative, $(1{+}a)(1{+}b){-}1$, not additive. Both nulls are shown.}')
    L.append('\\label{tab:composition}')
    L.append('\\begin{tabular}{lrr}')
    L.append('\\toprule')
    L.append('Quantity & $RLI_{\\mathrm{direct}}$ (\\%) & $RLI_{\\mathrm{proxy}}$ (\\%) \\\\')
    L.append('\\midrule')
    keys = [('psc', 'PSC alone'), ('vro', 'VRO alone'), ('combined', 'PSC + VRO (measured)'),
            ('additive_null', 'Additive null $a{+}b$'),
            ('multiplicative_null', 'Multiplicative null $(1{+}a)(1{+}b){-}1$'),
            ('excess_over_additive', 'Excess over additive null'),
            ('excess_over_multiplicative', 'Excess over multiplicative null')]
    for k, label in keys:
        d = abl.get('rli_direct', {})
        p = abl.get('rli_proxy', {})
        L.append('%s & %s & %s \\\\' % (label, pct(d.get(k)), pct(p.get(k))))
        if k == 'combined':
            L.append('\\midrule')
    L.append('\\bottomrule')
    L.append('\\end{tabular}\n\\end{table}')
    open(out, 'w').write('\n'.join(L) + '\n')
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--destiny-csv', default='results/destiny/results.csv')
    ap.add_argument('--lifetime-csv', default='results/lifetime_1MB.csv')
    ap.add_argument('--ablation-json', default='results/ablation_1MB.json')
    ap.add_argument('--outdir', default='results/tex')
    a = ap.parse_args()
    os.makedirs(a.outdir, exist_ok=True)
    made = []

    if os.path.exists(a.destiny_csv):
        rows = read_csv(a.destiny_csv)
        for road in ('HP', 'LOP'):
            if any(r['roadmap'] == road for r in rows):
                made.append(table_cross_tech(rows, 45, road, 'WriteEDP',
                            os.path.join(a.outdir, 'tab_crosstech_45nm_%s.tex' % road.lower())))
        made.append(table_relative(rows, 45, 'HP', 'WriteEDP', 'SRAM',
                    os.path.join(a.outdir, 'tab_rel_sram_45nm.tex')))
        made.append(table_relative(rows, 45, 'HP', 'WriteEDP', 'STT-MRAM',
                    os.path.join(a.outdir, 'tab_rel_stt_45nm.tex')))

    if os.path.exists(a.lifetime_csv):
        rows = read_csv(a.lifetime_csv)
        for arena in sorted({r['arena'] for r in rows}):
            made.append(table_lifetime(rows, arena,
                        os.path.join(a.outdir, 'tab_lifetime_%s.tex' % arena.replace('-', ''))))

    if os.path.exists(a.ablation_json):
        made.append(table_composition(json.load(open(a.ablation_json)),
                    os.path.join(a.outdir, 'tab_composition.tex')))

    for m in made:
        print('wrote', m)


if __name__ == '__main__':
    main()
